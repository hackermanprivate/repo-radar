"""Render a terminal session into an SVG for the README.

Deliberately dumb: it draws exactly the text it is given, so the demo asset in the
README is a real run and can be regenerated by anyone. No dependencies.

    python scripts/make_demo_svg.py --out docs/demo.svg -- <command to run>
"""

from __future__ import annotations

import argparse
import html
import subprocess
import sys

PAD_X, PAD_Y = 18, 54
LINE_H = 17
FONT_SIZE = 12.5
CHAR_W = 7.5


def run(command: list[str]) -> tuple[str, str]:
    result = subprocess.run(command, capture_output=True, text=True, timeout=120)
    return " ".join(command), (result.stdout or result.stderr).rstrip()


def render(shell: str, output: str) -> str:
    lines = output.splitlines() or [""]
    width = int(PAD_X * 2 + CHAR_W * max(len(line) for line in lines) + 24)
    width = max(width, 720)
    height = int(PAD_Y + LINE_H * len(lines) + PAD_Y)

    body = []
    for index, line in enumerate(lines):
        escaped = html.escape(line).replace(" ", "\u00a0")
        weight = ' font-weight="600"' if index == 0 else ""
        fill = "#8b949e" if line.startswith(("#", "-", "query:")) else "#e6edf3"
        body.append(
            f'<text x="{PAD_X}" y="{PAD_Y + LINE_H * index}" fill="{fill}"{weight} '
            f'font-family="ui-monospace,SFMono-Regular,Menlo,Consolas,monospace" '
            f'font-size="{FONT_SIZE}">{escaped}</text>'
        )

    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" role="img" aria-label="repo-radar terminal demo">
  <rect width="100%" height="100%" rx="10" fill="#0d1117"/>
  <rect width="100%" height="34" rx="10" fill="#161b22"/>
  <rect y="24" width="100%" height="10" fill="#161b22"/>
  <circle cx="18" cy="17" r="5.5" fill="#ff5f56"/>
  <circle cx="36" cy="17" r="5.5" fill="#ffbd2e"/>
  <circle cx="54" cy="17" r="5.5" fill="#27c93f"/>
  <text x="{width - 16}" y="21" text-anchor="end" fill="#8b949e"
        font-family="ui-monospace,SFMono-Regular,Menlo,Consolas,monospace" font-size="11">$ {html.escape(shell)}</text>
  {chr(10).join("  " + line for line in body)}
</svg>
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="docs/demo.svg")
    parser.add_argument("command", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    command = args.command[1:] if args.command and args.command[0] == "--" else args.command
    if not command:
        parser.error("give a command to capture after --")
    shell, output = run(command)
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(render(shell, output))
    print(f"wrote {args.out} ({len(output.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
